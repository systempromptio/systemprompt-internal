#!/usr/bin/env node
// Assembles playwright/artifact-shots/*.png into a single contact sheet.
//
// The PNGs are inlined as data URIs so the sheet is one self-contained file —
// it is meant to be published and looked at somewhere other than this checkout.
import * as fs from 'fs';
import * as path from 'path';

const shots = process.argv[2] ?? 'playwright/artifact-shots';
const out = process.argv[3] ?? 'playwright/artifact-shots/index.html';

const VIEWPORTS = ['light', 'dark', 'narrow'];
const files = fs.readdirSync(shots).filter((f) => f.endsWith('.png'));
if (files.length === 0) {
  console.error(`no PNGs in ${shots} — run the Playwright spec first`);
  process.exit(1);
}

const byType = new Map();
for (const file of files) {
  const m = /^(.+)-(light|dark|narrow)\.png$/.exec(file);
  if (!m) continue;
  const [, type, viewport] = m;
  if (!byType.has(type)) byType.set(type, {});
  byType.get(type)[viewport] = 'data:image/png;base64,'
    + fs.readFileSync(path.join(shots, file)).toString('base64');
}

const esc = (s) => s.replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));

const rows = [...byType.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([type, shots]) => `
  <section>
    <h2>${esc(type)}</h2>
    <div class="row">
      ${VIEWPORTS.map((v) => shots[v]
        ? `<figure class="${v}"><img src="${shots[v]}" alt="${esc(type)} in ${v}"><figcaption>${v}</figcaption></figure>`
        : `<figure class="missing"><div class="gap">not captured</div><figcaption>${v}</figcaption></figure>`).join('\n      ')}
    </div>
  </section>`).join('\n');

fs.writeFileSync(out, `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Artifact Gallery</title>
<style>
  :root { color-scheme: light dark;
    --bg: light-dark(#fdfcfb, #211a15); --surface: light-dark(#fff, #2b231d);
    --ink: light-dark(#241a12, #f6f1ec); --dim: light-dark(#6b5c50, #b3a496);
    --line: light-dark(#e8e0d8, #3d332b); --accent: oklch(0.67 0.18 50); }
  * { box-sizing: border-box; }
  body { margin: 0; padding: 2rem clamp(1rem, 4vw, 3rem); background: var(--bg); color: var(--ink);
    font: 15px/1.55 system-ui, -apple-system, "Segoe UI", Roboto, sans-serif; }
  header { border-bottom: 2px solid var(--accent); padding-bottom: 1rem; margin-bottom: 2rem; }
  h1 { margin: 0 0 .35rem; font-size: 1.6rem; letter-spacing: -0.02em; }
  header p { margin: 0; color: var(--dim); max-width: 60ch; }
  section { margin-bottom: 2.5rem; }
  h2 { font-size: 1rem; font-family: ui-monospace, Menlo, monospace; color: var(--accent);
    margin: 0 0 .75rem; }
  .row { display: grid; grid-template-columns: 1fr 1fr 24rem; gap: 1rem; align-items: start; }
  @media (max-width: 900px) { .row { grid-template-columns: 1fr; } }
  figure { margin: 0; background: var(--surface); border: 1px solid var(--line);
    border-radius: 1.125rem 0.375rem 1.125rem 1.125rem; overflow: hidden; }
  img { display: block; width: 100%; height: auto; }
  figcaption { padding: .5rem .75rem; font-size: .75rem; letter-spacing: .06em;
    text-transform: uppercase; color: var(--dim); border-top: 1px solid var(--line); }
  .gap { padding: 3rem 1rem; text-align: center; color: var(--dim); font-size: .85rem; }
</style>
</head>
<body>
<header>
  <h1>Artifact gallery</h1>
  <p>Every registered artifact type, rendered through the real MCP UI renderer with the
     Systemprompt Internal brand theme, then rasterized in light, dark and 375px-narrow.
     Generated by <code>just artifact-gallery</code>.</p>
</header>
${rows}
</body>
</html>
`);
console.log(`contact sheet → ${out} (${byType.size} types)`);
