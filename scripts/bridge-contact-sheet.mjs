#!/usr/bin/env node
// Assembles playwright/bridge-shots/*.png into a single contact sheet.
//
// Same idea as artifact-contact-sheet.mjs: the PNGs are inlined as data URIs so
// the sheet is one self-contained file that can be looked at, or handed to
// someone, away from this checkout. Here each PNG is one state of the bridge
// GUI, so the sheet is how you review a UI change across every state at once
// instead of clicking through them.
import * as fs from 'fs';
import * as path from 'path';

const shots = process.argv[2] ?? 'playwright/bridge-shots';
const out = process.argv[3] ?? 'playwright/bridge-shots/index.html';

// What each fixture is for. A sheet of unlabelled screenshots is a puzzle;
// naming the case is what makes a wrong one obvious.
const CAPTIONS = {
  'healthy': 'Both agents set up, governed and running — the good day.',
  'stale': 'A rotated loopback secret. One press of Repair should fix it.',
  'stale--after-repair': 'The same agent after Repair: generate, install and re-probe, one press.',
  'partial': 'A profile that applied only partly.',
  'app-missing': 'Codex CLI is not installed here, so it is offered under Add agent rather than listed.',
  'app-missing--add': 'The picker: what this installation permits, and what is already added.',
  'no-models': 'Installed and governed, but no provider key — nothing can actually run.',
  'proxy-down': 'A good install with the local proxy refusing connections.',
  'nothing-installed': 'No profile installed anywhere, so the first-run wizard owns the screen and the Agents tab never renders. Correct behaviour, not a gap.',
  'not-synced': 'Before the first sync the list is what this build registers, not what the installation permits — Add agent says so rather than implying authority.',
  'healthy--drawer': 'The per-agent drawer: health, models, and the actions.',
  'healthy--drawer-advanced': 'Technical detail expanded — every value the old card put on the first screen.',
};

const files = fs.readdirSync(shots).filter((f) => f.endsWith('.png')).sort();
if (files.length === 0) {
  console.error(`no PNGs in ${shots} — run \`just bridge-shots\` first`);
  process.exit(1);
}

const esc = (s) => s.replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));

const sections = files.map((file) => {
  const name = file.replace(/\.png$/, '');
  const src = 'data:image/png;base64,' + fs.readFileSync(path.join(shots, file)).toString('base64');
  const caption = CAPTIONS[name] ?? '';
  return `
  <section id="${esc(name)}">
    <h2>${esc(name)}</h2>
    ${caption ? `<p class="why">${esc(caption)}</p>` : ''}
    <figure><img src="${src}" alt="${esc(name)}" loading="lazy"></figure>
  </section>`;
}).join('\n');

const nav = files.map((f) => {
  const name = f.replace(/\.png$/, '');
  return `<a href="#${esc(name)}">${esc(name)}</a>`;
}).join('\n    ');

fs.writeFileSync(out, `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Bridge GUI states</title>
<style>
  :root { color-scheme: light dark;
    --bg: light-dark(#fdfcfb, #211a15); --surface: light-dark(#fff, #2b231d);
    --ink: light-dark(#241a12, #f6f1ec); --dim: light-dark(#6b5c50, #b3a496);
    --line: light-dark(#e8e0d8, #3d332b); --accent: oklch(0.67 0.18 50); }
  * { box-sizing: border-box; }
  body { margin: 0; padding: 2rem clamp(1rem, 4vw, 3rem); background: var(--bg); color: var(--ink);
    font: 15px/1.55 system-ui, -apple-system, "Segoe UI", Roboto, sans-serif; }
  header { border-bottom: 2px solid var(--accent); padding-bottom: 1rem; margin-bottom: 1.5rem; }
  h1 { margin: 0 0 .35rem; font-size: 1.6rem; letter-spacing: -0.02em; }
  header p { margin: 0; color: var(--dim); max-width: 68ch; }
  nav { display: flex; flex-wrap: wrap; gap: .4rem; margin-bottom: 2.5rem; }
  nav a { font: 12px ui-monospace, Menlo, monospace; text-decoration: none; color: var(--dim);
    border: 1px solid var(--line); border-radius: 999px; padding: .2rem .6rem; }
  nav a:hover { color: var(--accent); border-color: var(--accent); }
  section { margin-bottom: 3rem; scroll-margin-top: 1rem; }
  h2 { font-size: 1rem; font-family: ui-monospace, Menlo, monospace; color: var(--accent);
    margin: 0 0 .35rem; }
  .why { margin: 0 0 .75rem; color: var(--dim); max-width: 78ch; }
  figure { margin: 0; background: var(--surface); border: 1px solid var(--line);
    border-radius: 1.125rem 0.375rem 1.125rem 1.125rem; overflow: hidden; }
  img { display: block; width: 100%; height: auto; }
</style>
</head>
<body>
<header>
  <h1>Bridge GUI states</h1>
  <p>Every fixture the bridge preview ships, rendered through the real web tree and the real
     components with a mocked IPC. The desktop webview is Windows/macOS only, so this is how the
     GUI is reviewed anywhere else. Generated by <code>just bridge-shots</code>.</p>
</header>
<nav>
    ${nav}
</nav>
${sections}
</body>
</html>
`);
console.log(`contact sheet → ${out} (${files.length} states)`);
